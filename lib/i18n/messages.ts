export const messages: Record<Locale, Dict> = { ru, kk, en }

export type MessageKey = keyof typeof ru

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>
): string {
  const dict = messages[locale] || messages.ru
  let text = dict[key] ?? messages.ru[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}

/** Simple plural helper for product counts in RU/KK/EN */
export function productPlural(locale: Locale, n: number): string {
  if (locale === 'en') return n === 1 ? '' : 's'
  const m10 = n % 10
  const m100 = n % 100
  if (locale === 'kk') {
    // Kazakh often keeps the noun form; use empty/а/ов-like Russian pattern lightly
    if (m10 === 1 && m100 !== 11) return ''
    return ''
  }
  // Russian
  if (m10 === 1 && m100 !== 11) return ''
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return 'а'
  return 'ов'
}
